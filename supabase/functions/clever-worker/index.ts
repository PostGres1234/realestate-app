Deno.serve(async (req) => {
  if (req.method === "OPTIONS") return new Response("ok", { headers: CORS });

  try {
    const { messages, listings, focusPropertyId } = await req.json();

    const context = listings?.length
      ? `\n\nנכסים זמינים באפליקציה כרגע:\n${JSON.stringify(listings)}`
      : "";

    const system = (focusPropertyId ? SYSTEM_FOCUS : SYSTEM) + context;
    const convo = [...messages];

    let data = await callClaude(convo, system);

    for (let i = 0; i < 3 && data.stop_reason === "tool_use"; i++) {
      const toolUses = (data.content ?? []).filter((b: any) => b.type === "tool_use");
      convo.push({ role: "assistant", content: data.content });

      const toolResults = [];
      for (const tu of toolUses) {
        let result = { found: false };
        if (tu.name === "lookup_area_price") {
          const row = await lookupAreaPrice(tu.input.city, tu.input.neighborhood);
          result = row ? { found: true, ...row } : { found: false };
        }
        toolResults.push({
          type: "tool_result",
          tool_use_id: tu.id,
          content: JSON.stringify(result),
        });
      }
      convo.push({ role: "user", content: toolResults });
      data = await callClaude(convo, system);
    }

    let text = (data.content ?? []).map((b: any) => b.text ?? "").join("").trim();

    let ids: string[] = [];
    const match = text.match(/PROPERTIES:\s*(.+)$/m);
    if (match) {
      ids = match[1].split(",").map((s: string) => s.trim()).filter(Boolean);
      text = text.replace(/PROPERTIES:.*$/m, "").trim();
    }

    let options: string[] = [];
    const optMatch = text.match(/OPTIONS:\s*(.+)$/m);
    if (optMatch) {
      options = optMatch[1].split("|").map((s: string) => s.trim()).filter(Boolean);
      text = text.replace(/OPTIONS:.*$/m, "").trim();
    }

    const multi = /MULTI:\s*yes/m.test(text);
    text = text.replace(/MULTI:.*$/m, "").trim();

    // Every Jimmy-generated question can be skipped - only the app's
    // hardcoded opening message (never produced here) excludes it.
    return new Response(JSON.stringify({ text, ids, options, skippable: true, multi }), {
      headers: { "content-type": "application/json", ...CORS },
    });
  } catch (e) {
    console.log("function error", String(e));
    return new Response(
      JSON.stringify({ text: "אירעה שגיאה. נסו שוב.", ids: [], options: [], skippable: false, multi: false }),
      { headers: { "content-type": "application/json", ...CORS } }
    );
  }
});
